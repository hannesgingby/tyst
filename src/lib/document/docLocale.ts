export function getDocLocale(displayName: string | undefined): DocLocale {
	const code = LANGUAGE_CODE[displayName ?? DEFAULT_LANGUAGE] ?? "en";
	const overrides = LOCALES[code] ?? LOCALES[code.split("-")[0]] ?? {};
	return { ...EN, ...overrides };
}

export function headingPlaceholder(locale: DocLocale, level: HeadingMenuLevel): string {
	return level === 0 ? locale.title : locale.headings[level - 1];
}

/** Placeholder text for an empty block, derived from structure and document language. */
export function resolveBlockPlaceholder(
	locale: DocLocale,
	block: Block,
	prop?: string,
): string | undefined {
	if (prop) return prop;
	if (block.heading) return headingPlaceholder(locale, block.heading.level);
	if (block.list) return locale.listItem;
	if (block.footnote) return locale.footnote;
	if (block.outline) return locale.title;
	if (block.bibliography) return locale.bibliography;
	if (block.zoneKind === "header") return locale.pageHeader;
	if (block.zoneKind === "footer") return locale.pageFooter;
	return block.placeholder;
}
