export interface DocLocale {
	/** Lowercase prefix for page-form references: "page", "sida", "Seite", … */
	page: string;
	/** Title-case word for figure references: "Figure", "Figur", "Abbildung", … */
	figure: string;
	/** Default bibliography/sources heading, matching Typst's built-in default. */
	bibliography: string;
	/** Outline / document title block (#title). */
	title: string;
	/** Empty heading blocks, levels 1–4. */
	headings: readonly [string, string, string, string];
	/** Fallback label for an empty heading reference target. */
	heading: string;
	/** Empty list item block. */
	listItem: string;
	/** Empty footnote body block. */
	footnote: string;
	/** Empty page header zone block. */
	pageHeader: string;
	/** Empty page footer zone block. */
	pageFooter: string;
	/** Shown in the sole empty body block of a new document. */
	startWriting: string;
}

